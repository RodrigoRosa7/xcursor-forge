"""Command line interface: ``xcursor-forge styles|build|preview``."""

from __future__ import annotations

import argparse
import os
import re
import shutil
import sys
from pathlib import Path

import numpy as np

from . import __version__, xcursor
from .png import write_png
from .styles import STYLES

USER_ICONS = Path.home() / ".local/share/icons"
SEARCH_DIRS = [USER_ICONS, Path.home() / ".icons", Path("/usr/local/share/icons"), Path("/usr/share/icons")]
SAFE_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*$")  # no leading dot: rules out "." / ".."


def find_theme(spec: str) -> Path:
    """Accept a theme directory or a theme name searched in the usual icon dirs."""
    p = Path(spec).expanduser()
    if (p / "cursors").is_dir():
        return p.resolve()
    if "/" not in spec:
        for d in SEARCH_DIRS:
            if (d / spec / "cursors").is_dir():
                return (d / spec).resolve()
    raise SystemExit(f"error: no cursor theme found for '{spec}' (looked for <theme>/cursors)")


def theme_display_name(theme: Path) -> str:
    index = theme / "index.theme"
    if index.is_file():
        for line in index.read_text(errors="replace").splitlines():
            if line.strip().startswith("Name="):
                return line.split("=", 1)[1].strip()
    return theme.name


def cmd_styles(_args) -> int:
    for s in STYLES.values():
        print(f"{s.name:14} {s.description}")
    return 0


def cmd_build(args) -> int:
    base = find_theme(args.base)
    style = STYLES[args.style]
    name = args.name or f"{base.name}-{style.name}"
    if not SAFE_NAME.match(name):
        raise SystemExit(f"error: invalid theme name '{name}' (use letters, digits, . _ + -)")
    out_root = USER_ICONS if args.install else Path(args.out).expanduser()
    dest = out_root / name
    if dest.resolve() == base:
        raise SystemExit("error: output would overwrite the base theme")
    if dest.exists():
        if not args.force:
            raise SystemExit(f"error: {dest} exists (use --force to replace it)")
        shutil.rmtree(dest)

    src = base / "cursors"
    staging = out_root / f".{name}.partial"
    if staging.exists():
        shutil.rmtree(staging)
    (staging / "cursors").mkdir(parents=True)

    built = linked = skipped = 0
    for entry in sorted(src.iterdir()):
        target = staging / "cursors" / entry.name
        if entry.is_symlink():
            link = os.readlink(entry)
            # keep links that stay inside the cursors dir; materialize the rest
            if "/" not in link and (src / link).exists():
                target.symlink_to(link)
                linked += 1
                continue
        if not entry.is_file():
            continue
        try:
            frames = xcursor.read(entry)
        except (xcursor.XcursorError, OSError) as exc:
            print(f"warning: skipping {entry.name}: {exc}", file=sys.stderr)
            skipped += 1
            continue
        xcursor.write(target, style.render(entry.name, frames, args.intensity))
        built += 1
        if not args.quiet:
            print(f"\r  {built} cursors", end="", flush=True)
    if not args.quiet:
        print()

    base_name = theme_display_name(base)
    (staging / "index.theme").write_text(
        "[Icon Theme]\n"
        f"Name={name}\n"
        f"Comment={style.name} style of {base_name}, generated by xcursor-forge {__version__}\n"
        f"Inherits={base.name}\n"
    )
    (staging / "GENERATED.txt").write_text(
        f"Generated by xcursor-forge {__version__} (style: {style.name}, intensity: {args.intensity})\n"
        f"Base theme: {base_name} ({base})\n\n"
        "This theme is a modified version of the base theme's artwork.\n"
        "It is distributed under the base theme's license, not xcursor-forge's.\n"
    )
    staging.rename(dest)
    print(f"{dest}  ({built} cursors, {linked} aliases, {skipped} skipped)")
    if args.install:
        print(f"Installed. Select '{name}' as cursor theme (niri: cursor {{ xcursor-theme \"{name}\" }}).")
    return 0


def cmd_preview(args) -> int:
    base = find_theme(args.base)
    style = STYLES[args.style]
    path = base / "cursors" / args.cursor
    if not path.exists():
        raise SystemExit(f"error: {path} not found")
    frames = xcursor.read(path)
    sizes = sorted({f.size for f in frames})
    size = min(sizes, key=lambda s: abs(s - args.size))
    original = [f for f in frames if f.size == size]
    styled = [f for f in style.render(path.name, frames, args.intensity) if f.size == size]
    tiles = [original[0]] + styled
    bg = np.array([0x1A, 0x1B, 0x26, 255], np.float32) / 255
    pad = max(4, size // 6)
    h = max(t.rgba.shape[0] for t in tiles) + 2 * pad
    w = sum(t.rgba.shape[1] + 2 * pad for t in tiles)
    canvas = np.tile(bg, (h, w, 1))
    x = 0
    for t in tiles:
        th, tw, _ = t.rgba.shape
        a = t.rgba[..., 3:4]
        region = canvas[pad:pad + th, x + pad:x + pad + tw]
        region[..., :3] = t.rgba[..., :3] * a + region[..., :3] * (1 - a)
        x += tw + 2 * pad
    canvas = canvas.repeat(args.scale, 0).repeat(args.scale, 1)
    write_png(args.output, canvas)
    print(f"{args.output}  (size {size}: original + {len(styled)} styled frame(s))")
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="xcursor-forge",
                                description="Generate styled variants of existing Xcursor themes.")
    p.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = p.add_subparsers(dest="command", required=True)

    sub.add_parser("styles", help="list available styles").set_defaults(func=cmd_styles)

    b = sub.add_parser("build", help="build a styled theme from a base theme")
    b.add_argument("base", help="base theme name (e.g. Adwaita) or path to a theme directory")
    b.add_argument("-s", "--style", choices=STYLES, required=True)
    b.add_argument("-n", "--name", help="output theme name (default: <base>-<style>)")
    b.add_argument("-o", "--out", default="dist", help="output directory (default: ./dist)")
    b.add_argument("-i", "--install", action="store_true", help=f"write into {USER_ICONS}")
    b.add_argument("--intensity", type=float, default=1.0, help="effect strength multiplier (default 1.0)")
    b.add_argument("-f", "--force", action="store_true", help="replace an existing output theme")
    b.add_argument("-q", "--quiet", action="store_true")
    b.set_defaults(func=cmd_build)

    v = sub.add_parser("preview", help="render one cursor (original + styled frames) to a PNG")
    v.add_argument("base")
    v.add_argument("-s", "--style", choices=STYLES, required=True)
    v.add_argument("-c", "--cursor", default="default", help="cursor file name (default: default)")
    v.add_argument("--size", type=int, default=48, help="nominal size, nearest available is used")
    v.add_argument("--scale", type=int, default=4, help="integer upscale for viewing (default 4)")
    v.add_argument("--intensity", type=float, default=1.0)
    v.add_argument("-o", "--output", default="preview.png")
    v.set_defaults(func=cmd_preview)

    args = p.parse_args(argv)
    if getattr(args, "intensity", 1.0) <= 0:
        p.error("--intensity must be positive")
    return args.func(args)
